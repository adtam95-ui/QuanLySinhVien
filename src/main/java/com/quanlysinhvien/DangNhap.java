    private void btnDangNhapActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDangNhapActionPerformed
        String taiKhoan = txtTaiKhoan.getText().trim();
String matKhau = new String(txtMatKhau.getPassword());
System.out.println("Tai khoan nhap: [" + taiKhoan + "]");

if (taiKhoan.isEmpty() || matKhau.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Vui lòng nhập tài khoản và mật khẩu!"
    );
    return;
}

String sql = "SELECT COUNT(*) FROM TaiKhoan "
        + "WHERE TenDangNhap = ? "
        + "AND MatKhauHash = CONVERT(VARCHAR(64), "
        + "HASHBYTES('SHA2_256', CONVERT(NVARCHAR(4000), ?)), 2)";

try (java.sql.Connection conn = KetNoiSQL.ketNoi();
     java.sql.PreparedStatement ps = conn.prepareStatement(sql)) {

    ps.setString(1, taiKhoan);
    ps.setString(2, matKhau);

    try (java.sql.ResultSet rs = ps.executeQuery()) {
        if (rs.next() && rs.getInt(1) > 0) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Đăng nhập thành công!"
            );

            new TrangChu().setVisible(true);
            this.dispose();

        } else {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Sai tài khoản hoặc mật khẩu!"
            );
            txtMatKhau.setText("");
        }
    }

} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Lỗi: " + e.getMessage()
    );
}
    }//GEN-LAST:event_btnDangNhapActionPerformed

