    private void btnXoaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnXoaActionPerformed
        String maSV = txtMaSV.getText().trim();

if (maSV.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this, "Vui lòng nhập mã sinh viên cần xóa!");
    return;
}

int chon = javax.swing.JOptionPane.showConfirmDialog(
    this,
    "Bạn có chắc muốn xóa sinh viên " + maSV + "?",
    "Xác nhận xóa",
    javax.swing.JOptionPane.YES_NO_OPTION
);

if (chon != javax.swing.JOptionPane.YES_OPTION) {
    return;
}

String sql = "DELETE FROM SinhVien WHERE MaSV = ?";

try (java.sql.Connection conn = KetNoiSQL.ketNoi();
     java.sql.PreparedStatement ps = conn.prepareStatement(sql)) {

    ps.setString(1, maSV);

    int ketQua = ps.executeUpdate();

    if (ketQua > 0) {
        javax.swing.JOptionPane.showMessageDialog(this, "Xóa sinh viên thành công!");
        taiDanhSachSinhVien();
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Không tìm thấy mã sinh viên!");
    }

} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(this, "Lỗi: " + e.getMessage());
}
    }//GEN-LAST:event_btnXoaActionPerformed

    private void btnSuaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSuaActionPerformed
       try {
    String maSV = txtMaSV.getText().trim();

    if (maSV.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Vui lòng nhập Mã sinh viên cần sửa!");
        return;
    }

    String sql = "UPDATE SinhVien SET HoTen=?, NgaySinh=?, GioiTinh=?, "
            + "DiaChi=?, SDT=?, Email=?, MaLop=? WHERE MaSV=?";

    try (java.sql.Connection conn = KetNoiSQL.ketNoi();
         java.sql.PreparedStatement ps = conn.prepareStatement(sql)) {

        ps.setString(1, txtHoTen.getText().trim());
        ps.setDate(2, java.sql.Date.valueOf(txtNgaySinh.getText().trim()));
        ps.setString(3, txtGioiTinh.getText().trim());
        ps.setString(4, txtDiaChi.getText().trim());
        ps.setString(5, txtSDT.getText().trim());
        ps.setString(6, txtEmail.getText().trim());
        ps.setString(7, txtMaLop.getText().trim());
        ps.setString(8, maSV);

        int ketQua = ps.executeUpdate();

        if (ketQua > 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Sửa sinh viên thành công!");
            taiDanhSachSinhVien();
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Không tìm thấy mã sinh viên!");
        }
    }

} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(this, "Lỗi: " + e.getMessage());
}
    }//GEN-LAST:event_btnSuaActionPerformed

