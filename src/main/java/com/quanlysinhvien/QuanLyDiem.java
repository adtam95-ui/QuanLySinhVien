private void taiDanhSachDiem() {
    String sql = "SELECT MaSV, MaMon, Diem FROM Diem";

    javax.swing.table.DefaultTableModel model =
        (javax.swing.table.DefaultTableModel) tblDiem.getModel();

    model.setRowCount(0);

    try (java.sql.Connection conn = KetNoiSQL.ketNoi();
         java.sql.PreparedStatement ps = conn.prepareStatement(sql);
         java.sql.ResultSet rs = ps.executeQuery()) {

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getString("MaSV"),
                rs.getString("MaMon"),
                rs.getDouble("Diem")
            });
        }

    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Lỗi tải điểm: " + e.getMessage()
        );
    }
}
