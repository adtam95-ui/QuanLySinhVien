    private void btnThemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnThemActionPerformed
        String maSV = txtMaSV.getText().trim();
String maMon = txtMaMon.getText().trim();
String diemNhap = txtDiem.getText().trim();

if (maSV.isEmpty() || maMon.isEmpty() || diemNhap.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Vui lòng nhập đầy đủ thông tin!"
    );
    return;
}

double diem;

try {
    diem = Double.parseDouble(diemNhap);
} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Điểm phải là số! Ví dụ: 8.5"
    );
    return;
}

if (diem < 0 || diem > 10 || !Double.isFinite(diem)) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Điểm phải nằm trong khoảng 0 đến 10!"
    );
    return;
}

String sql = "INSERT INTO Diem (MaSV, MaMon, Diem) VALUES (?, ?, ?)";

try (java.sql.Connection conn = KetNoiSQL.ketNoi();
     java.sql.PreparedStatement ps = conn.prepareStatement(sql)) {

    ps.setString(1, maSV);
    ps.setString(2, maMon);
    ps.setDouble(3, diem);

    ps.executeUpdate();

    javax.swing.JOptionPane.showMessageDialog(
        this, "Thêm điểm thành công!"
    );

    taiDanhSachDiem();

} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Lỗi: " + e.getMessage()
    );
}
    }//GEN-LAST:event_btnThemActionPerformed

    private void btnSuaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSuaActionPerformed
       String maSV = txtMaSV.getText().trim();
String maMon = txtMaMon.getText().trim();
String diemNhap = txtDiem.getText().trim();

if (maSV.isEmpty() || maMon.isEmpty() || diemNhap.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Vui lòng nhập đầy đủ thông tin!"
    );
    return;
}

double diem;

try {
    diem = Double.parseDouble(diemNhap);
} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Điểm phải là số!"
    );
    return;
}

if (!Double.isFinite(diem) || diem < 0 || diem > 10) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Điểm phải từ 0 đến 10!"
    );
    return;
}

String sql = "UPDATE Diem SET Diem = ? WHERE MaSV = ? AND MaMon = ?";

try (java.sql.Connection conn = KetNoiSQL.ketNoi();
     java.sql.PreparedStatement ps = conn.prepareStatement(sql)) {

    ps.setDouble(1, diem);
    ps.setString(2, maSV);
    ps.setString(3, maMon);

    int ketQua = ps.executeUpdate();

    if (ketQua > 0) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Sửa điểm thành công!"
        );
        taiDanhSachDiem();
    } else {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Không tìm thấy điểm cần sửa!"
        );
    }

} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Lỗi: " + e.getMessage()
    );
}
    }//GEN-LAST:event_btnSuaActionPerformed

    private void btnXoaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnXoaActionPerformed
       String maSV = txtMaSV.getText().trim();
String maMon = txtMaMon.getText().trim();

if (maSV.isEmpty() || maMon.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Vui lòng nhập mã sinh viên và mã môn học!"
    );
    return;
}

int xacNhan = javax.swing.JOptionPane.showConfirmDialog(
    this,
    "Bạn có chắc muốn xóa điểm này?",
    "Xác nhận xóa",
    javax.swing.JOptionPane.YES_NO_OPTION
);

if (xacNhan != javax.swing.JOptionPane.YES_OPTION) {
    return;
}

String sql = "DELETE FROM Diem WHERE MaSV = ? AND MaMon = ?";

try (java.sql.Connection conn = KetNoiSQL.ketNoi();
     java.sql.PreparedStatement ps = conn.prepareStatement(sql)) {

    ps.setString(1, maSV);
    ps.setString(2, maMon);

    int ketQua = ps.executeUpdate();

    if (ketQua > 0) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Xóa điểm thành công!"
        );

        txtMaSV.setText("");
        txtMaMon.setText("");
        txtDiem.setText("");

        taiDanhSachDiem();

    } else {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Không tìm thấy điểm cần xóa!"
        );
    }

} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Lỗi: " + e.getMessage()
    );
}
    }//GEN-LAST:event_btnXoaActionPerformed

    private void tblDiemMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblDiemMouseClicked
        int dong = tblDiem.getSelectedRow();

if (dong >= 0) {
    int dongModel = tblDiem.convertRowIndexToModel(dong);

    txtMaSV.setText(
        tblDiem.getModel().getValueAt(dongModel, 0).toString()
    );

    txtMaMon.setText(
        tblDiem.getModel().getValueAt(dongModel, 1).toString()
    );

    txtDiem.setText(
        tblDiem.getModel().getValueAt(dongModel, 2).toString()
    );
}
    }//GEN-LAST:event_tblDiemMouseClicked

